// Helper: Menghasilkan pesanan awal dinamis untuk setiap SPPG yang ada di Jawa Timur
export function getInitialOrdersForSppg(dapur: DapurMbgWilayah): PesananMbgPuskesmas[] {
  const pList = dapur.posyanduSasaran && dapur.posyanduSasaran.length > 0
    ? dapur.posyanduSasaran
    : ["Posyandu Mawar 01", "Posyandu Melati 01", "Posyandu Dahlia 01", "Posyandu Kenanga 01"];

  const statuses: StatusPesananMbg[] = ["Diterima", "Diproses", "Diantar", "Selesai"];
  const orders: PesananMbgPuskesmas[] = [];

  const safeLimit = Math.min(pList.length, 4);

  for (let i = 0; i < safeLimit; i++) {
    const rawName = pList[i];
    const matchDesa = rawName.match(/\((.*?)\)/);
    const desaName = matchDesa ? matchDesa[1] : `Desa ${dapur.kecamatanLayanan[0] || "Binaan"} 0${i + 1}`;
    const cleanPosyandu = rawName.split("(")[0].trim();
    const st = statuses[i % statuses.length];

    // Standardisasi kuota porsi MBG maksimal 10 balita/porsi per posyandu agar sinkron 100%
    const isMawar01 = rawName.includes("Mawar 01");
    const pA = isMawar01 ? 6 : i % 2 === 0 ? 7 : 8;
    const pB = isMawar01 ? 4 : i % 2 === 0 ? 3 : 2;
    const pC = 0;
    const tot = pA + pB + pC;

    const shortId = dapur.id.replace("SPPG-", "");
    const poNum = `PO-MBG/PSK-${shortId}/202611/${String(40 + i + 1).padStart(3, "0")}`;

    const newOrder: PesananMbgPuskesmas = {
      id: `PO-${dapur.id}-${i + 1}`,
      nomorPo: poNum,
      puskesmasPemesan: `Puskesmas ${dapur.kecamatanLayanan[0] || dapur.kabupaten}`,
      sppgDituju: dapur.namaDapur,
      sppgId: dapur.id,
      posyanduTarget: rawName,
      desa: desaName,
      kecamatan: dapur.kecamatanLayanan[0] || "Kecamatan Binaan",
      tglPenyaluran: i === 0 ? "Hari ini, 14 Nov 2026" : "Hari ini, 14 Nov 2026",
      sesiPenyaluran: i % 2 === 0 ? "Sesi Pagi (09:00 WIB)" : "Sesi Siang (11:30 WIB)",
      jumlahPaketA: pA,
      jumlahPaketB: pB,
      jumlahPaketC: pC,
      totalPorsi: tot,
      catatanKlinis: i === 1
        ? "Prioritas Paket B: 2 balita faltering terdeteksi kurva kuning KMS bulan ini."
        : "Pastikan wadah makanan higienis hangat suhu min 60°C.",
      statusPesanan: st,
      tglDibuat: "Hari ini, 06:45 WIB",
      jamDiterima: st !== "Diajukan ke SPPG" ? "07:10 WIB" : undefined,
      jamDiproses: st === "Diproses" || st === "Diantar" || st === "Selesai" ? "07:45 WIB" : undefined,
      jamDiantar: st === "Diantar" || st === "Selesai" ? "08:30 WIB" : undefined,
      jamSelesai: st === "Selesai" ? "09:15 WIB" : undefined,
      kurirArmada: i % 2 === 0 ? "Mobil Box Termal #01" : "Motor Termal Kurir #02",
      verifikasiPosyandu: st === "Selesai" ? {
        waktuTiba: "Hari ini, 09:15 WIB",
        kaderPenerima: `Kader ${cleanPosyandu}`,
        paketADiterima: pA,
        paketBDiterima: pB,
        paketCDiterima: pC,
        totalDiterima: tot,
        kondisiMakanan: "Sangat Baik & Hangat (Suhu 64°C)",
        catatanPenerima: "Ransum lengkap, lauk telur omega & lele diterima utuh dalam kondisi prima.",
      } : undefined,
    };

    orders.push(newOrder);
  }

  return orders;
}


