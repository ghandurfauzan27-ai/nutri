// Helper: Otomatisasi Alokasi SPPG Terdekat berdasarkan Wilayah (Kecamatan & Kabupaten)
// Puskesmas / Posyandu TIDAK PERLU MEMILIH MANUAL, sistem NutriTrack langsung mengarahkan ke dapur terdekat!
export function getClosestSppgForWilayah(kabupaten: string, kecamatan: string): DapurMbgWilayah {
  const normKec = (kecamatan || "").toLowerCase().trim();
  const normKab = (kabupaten || "").toLowerCase().trim();

  // 1. Cocokkan spesifik kecamatan layanan
  const matchKec = MASTER_DAPUR_MBG.find(
    (d) =>
      d.kabupaten.toLowerCase().includes(normKab) ||
      normKab.includes(d.kabupaten.toLowerCase()) ||
      d.kecamatanLayanan.some((k) => k.toLowerCase() === normKec || normKec.includes(k.toLowerCase()))
  );
  if (matchKec) return matchKec;

  // 2. Cocokkan kabupaten
  const matchKab = MASTER_DAPUR_MBG.find(
    (d) => d.kabupaten.toLowerCase() === normKab || normKab.includes(d.kabupaten.toLowerCase().replace("kab. ", "").replace("kota ", ""))
  );
  if (matchKab) return matchKab;

  // 3. Fallback default SPPG Socah / Bangkalan
  return MASTER_DAPUR_MBG[0];
}

